CREATE TABLE transactions (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    type VARCHAR(16) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    name VARCHAR(255) NULL,
    category_id BIGINT NOT NULL,
    business_time DATETIME(0) NOT NULL,
    first_saved_at_utc DATETIME(6) NOT NULL,
    first_save_order BIGINT NOT NULL,
    updated_at_utc DATETIME(6) NOT NULL,
    remark TEXT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_transactions_account_order UNIQUE (account_id, first_save_order),
    CONSTRAINT fk_transactions_account FOREIGN KEY (account_id, user_id) REFERENCES accounts (id, user_id),
    CONSTRAINT fk_transactions_category FOREIGN KEY (category_id, user_id, type) REFERENCES categories (id, user_id, type),
    CONSTRAINT ck_transactions_amount CHECK (amount <> 0),
    CONSTRAINT ck_transactions_type CHECK (type IN ('INCOME', 'EXPENSE')),
    CONSTRAINT ck_transactions_order CHECK (first_save_order > 0),
    INDEX idx_transactions_ledger (account_id, business_time, first_save_order),
    INDEX idx_transactions_month_type (account_id, type, business_time),
    INDEX idx_transactions_category_month (account_id, category_id, business_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
